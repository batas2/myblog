<?php
/**
 * tools/preview_admin.php — a throwaway copy of the site with a known admin
 * password and synthetic traffic, served on localhost.
 *
 * The admin dashboard cannot be judged from source: the Scores tab only makes
 * sense with real posts standing next to recorded pageviews, and the password
 * on this machine is not something a tool should ask for. This builds that
 * picture in a sandbox and leaves the real content/ untouched.
 *
 *   php tools/preview_admin.php            sync + serve on :8830, password 'preview'
 *   php tools/preview_admin.php --port=... pick another port
 *   php tools/preview_admin.php --keep     serve what is already there, sync nothing
 *   php tools/preview_admin.php --sync     push source edits into a running sandbox and exit
 *
 * Never run this on the server: it writes a config.php with a known password.
 */

declare(strict_types=1);

$root = dirname(__DIR__);
$port = 8830;
$keep = false;
$syncOnly = false;
foreach (array_slice($argv, 1) as $arg) {
    if (preg_match('/^--port=(\d+)$/', $arg, $m)) $port = (int) $m[1];
    elseif ($arg === '--keep') $keep = true;
    elseif ($arg === '--sync') $syncOnly = true;
    else { fwrite(STDERR, "unknown option: {$arg}\n"); exit(1); }
}
$box = sys_get_temp_dir() . '/bfrackowiak-preview';
$seeded = false;
const PREVIEW_PW = 'preview';

/* Sources re-sync on every start (edit, restart, look) while the seeded
   analytics survive: rebuilding 2000 synthetic hits to re-check a CSS change
   is the kind of wait that stops you from checking. */
if (!$keep) {
    echo "syncing sources into {$box}\n";
    // config.php and the router are sandbox-local: never overwritten from the
    // repo (that would hand the sandbox the real secrets) and never deleted.
    // The leading slash matters: an unanchored --exclude=config.php matches at
    // any depth and takes lib/config.php with it, which is the loader every
    // entrypoint requires, so the sandbox build dies before it starts.
    exec('rsync -a --delete --exclude=_remote-backup/ --exclude=_archive/ --exclude=.git/ --exclude=.claude/ '
       . '--exclude=/config.php --exclude=/preview-router.php '
       . '--exclude=content/comments/ --exclude=content/analytics.db --exclude=content/analytics.db-* '
       . '--exclude=content/analytics.seed --exclude=content/newsletter.db --exclude=content/newsletter.db-* '
       . '--exclude=content/scores.db --exclude=content/scores.db-* '
       . escapeshellarg($root . '/') . ' ' . escapeshellarg($box . '/'), $o, $rc);
    if ($rc !== 0) { fwrite(STDERR, "rsync failed\n"); exit(1); }
    @mkdir($box . '/content/comments', 0755, true);

    if (!is_file($box . '/config.php')) {
        $cfg = require $root . '/config.example.php';
        file_put_contents($box . '/config.php', '<?php return ' . var_export(array_merge($cfg, [
            'admin_user'          => 'preview',
            'admin_password_hash' => password_hash(PREVIEW_PW, PASSWORD_DEFAULT),
            'stats_key'           => 'preview',
            'php_bin'             => PHP_BINARY,
            'analytics_exclude_ips' => [],
        ]), true) . ";\n");
    }

    /* Auto-login router, sandbox copy only: headless screenshot tools cannot
       POST a login form, and the real admin must keep requiring one. ?preview=1
       on any URL opens the session, then the request is served as usual and
       normal auth applies. admin.php itself is never patched. */
    $router = <<<'PHP'
    <?php
    /* generated by tools/preview_admin.php — sandbox only, never deployed */
    if (($_GET['preview'] ?? '') === '1') {
        require_once __DIR__ . '/lib/config.php';
        require_once __DIR__ . '/lib/helpers.php';
        require_once __DIR__ . '/lib/admin.php';
        admin_login('preview', '__PW__', '127.0.0.1');
    }
    return false;   // hand the request back to the built-in server
    PHP;
    file_put_contents($box . '/preview-router.php', str_replace('__PW__', PREVIEW_PW, $router) . "\n");

    exec('cd ' . escapeshellarg($box) . ' && ' . PHP_BINARY . ' tools/build.php 2>&1', $out, $rc);
    echo implode("\n", $out), "\n";
    if ($rc !== 0) { fwrite(STDERR, "build failed\n"); exit(1); }

    /* Synthetic traffic. Deterministic (seeded) so two runs look the same, and
       shaped so the Scores tab has something to say: high-reach posts mostly
       get more views, with two deliberate outliers in each direction. */
    require_once $box . '/lib/config.php';
    require_once $box . '/lib/helpers.php';
    require_once $box . '/lib/markdown.php';
    require_once $box . '/lib/blog.php';
    require_once $box . '/lib/analytics.php';
    require_once $box . '/lib/scores.php';

    $db = an_db();
    $seeded = (int) $db->query('SELECT COUNT(*) FROM hits')->fetchColumn() > 0;
}
if ($syncOnly) { echo "sandbox synced\n"; exit(0); }

if (!$keep && !$seeded) {
    $posts = array_values(array_filter(load_posts(true), fn(array $p): bool => $p['status'] === 'published'));
    mt_srand(20260727);
    $refs = [['', ''], ['news.ycombinator.com', 'news'], ['www.linkedin.com', 'social'], ['www.google.com', 'search']];
    $uas = [
        ['Chrome', 'Windows', 'desktop'], ['Safari', 'iOS', 'mobile'],
        ['Firefox', 'Linux', 'desktop'], ['Safari', 'macOS', 'desktop'],
    ];
    $countries = ['pl', 'us', 'de', 'gb', 'nl', 'in'];
    $st = $db->prepare('INSERT INTO hits (day, ts, path, ref, ref_group, utm_source, utm_medium, utm_campaign,
        country, browser, os, device, lang, screen, tz, visitor, duration)
        VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)');
    $rows = 0;
    foreach ($posts as $i => $p) {
        $reach = sc_reach($p['scores'] ?? []) ?? 5.0;
        $base = (int) round(($reach - 3) * 26);
        if ($i === 1) $base = 8;              // a strong post nobody found — the distribution failure
        if ($i === 4) $base = 190;            // a mediocre post that took off — the model's blind spot
        $n = max(3, $base + mt_rand(-12, 12));

        /* Where this post was hand-carried. A post that declares a Medium or DEV
           URL gets clicks from there; every post gets the two destinations that
           never have a URL of their own. Without this the whole tagged-link
           story (share_urls, the Acquisition groups, the Published-on column)
           renders as a column of dots and cannot be judged. */
        $carried = ['linkedin', 'newsletter'];
        foreach (array_keys($p['syndication']) as $platform) {
            $key = strtolower($platform);
            if (isset(SHARE_TARGETS[$key])) $carried[] = $key;
        }

        for ($h = 0; $h < $n; $h++) {
            $ts = time() - mt_rand(0, 29 * 86400);
            [$ref, $grp] = $refs[mt_rand(0, 3)];
            [$br, $os, $dev] = $uas[mt_rand(0, 3)];
            // one hit in five arrives on a tagged link, and those carry no
            // referrer at all — which is exactly why the tag has to be there
            $src = $mdm = $cmp = '';
            if (mt_rand(1, 5) === 1) {
                $src = $carried[mt_rand(0, count($carried) - 1)];
                $mdm = SHARE_TARGETS[$src]['medium'];
                $cmp = $p['slug'];
                $ref = '';
                $grp = an_utm_group($src);
            }
            $st->execute([
                gmdate('Y-m-d', $ts), $ts, post_path($p['slug']), $ref, $grp, $src, $mdm, $cmp,
                $countries[mt_rand(0, 5)], $br, $os, $dev, 'en', $dev === 'mobile' ? 'phone' : 'laptop',
                'Europe/Warsaw', substr(md5((string) mt_rand()), 0, 16), mt_rand(0, 1) ? mt_rand(20, 400) : 0,
            ]);
            $rows++;
        }
    }
    echo "seeded {$rows} synthetic hits across " . count($posts) . " posts\n";
}

echo "\n  admin:  http://127.0.0.1:{$port}/admin.php   login: preview   password: " . PREVIEW_PW . "\n";
echo "  scores: http://127.0.0.1:{$port}/admin.php?days=30&sort=date#scores\n";
echo "  site:   http://127.0.0.1:{$port}/\n\n";
// opcache off for the same reason the integration suite disables it: edits to
// the copied sources must show up on the next request, not two seconds later
passthru('cd ' . escapeshellarg($box) . ' && ' . escapeshellarg(PHP_BINARY)
    . ' -d opcache.enable=0 -d opcache.enable_cli=0 -S 127.0.0.1:' . $port . ' preview-router.php');
